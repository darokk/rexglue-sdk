#!/usr/bin/env python3
"""Generate the four-lane form of the scalar terrain shader."""

import argparse
import re
from pathlib import Path


directory = Path(__file__).resolve().parents[1] / "src/graphics/fable2"
source = directory / "fable2_terrain_tess_vs.inc"
destination = directory / "fable2_terrain_tess_vs_simd.inc"


def predicate_block(match):
    predicate, body = match.groups()
    statements = []
    for statement in body.split(";"):
        statement = statement.strip()
        if not statement:
            continue
        if statement.startswith("const "):
            statements.append(statement)
            continue
        assignment = re.fullmatch(r"(r\[\d+\]\[\d+\]|ps|p0) = (.+)", statement)
        if not assignment:
            raise ValueError(f"Unsupported predicated statement: {statement}")
        target, value = assignment.groups()
        value = value.replace("sample(", f"sample({predicate}, ")
        statements.append(f"{target} = {predicate} ? ({value}) : {target}")
    return f"if (AnyLane({predicate})) {{ " + "; ".join(statements) + "; }"


def generate():
    code = "\n".join(line for line in source.read_text().splitlines() if not line.startswith("//"))
    for scalar, vector in (
        ("const float ", "const TerrainFloat "),
        ("const bool ", "const TerrainMask "),
        ("std::fabs(", "__builtin_elementwise_abs("),
        ("std::floor(", "__builtin_elementwise_floor("),
        ("std::min(", "TerrainMin("),
        ("std::max(", "TerrainMax("),
    ):
        code = code.replace(scalar, vector)
    code = re.sub(r"if \((p0(?:_start)?)\) \{([^{}]*)\}", predicate_block, code)
    if re.search(r"\bif \((?!AnyLane\()|std::|\bconst (?:float|bool)\b", code):
        raise ValueError("Unexpected scalar operation in the generated terrain shader")
    return (
        "// Generated by tools/generate_terrain_tess_simd.py from fable2_terrain_tess_vs.inc.\n"
        "// Predicated stores keep the previous register in inactive lanes.\n"
        + code
        + "\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if regeneration changes the file")
    args = parser.parse_args()
    output = generate()
    if args.check:
        if destination.read_text() != output:
            parser.exit(1, f"Regenerate {destination.name}.\n")
    else:
        destination.write_text(output, newline="\n")
